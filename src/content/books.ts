export function bookForChoice(
  stage: 'miller' | 'mara' | 'evening' | 'complete',
  nodeId: string,
  optionId: string,
): Book | undefined {
  if (nodeId !== 'order') return undefined;
  if (stage === 'miller' && !['orchard', 'witnesses'].includes(optionId)) return undefined;
  if (stage === 'mara' && !['station', 'roads', 'letters'].includes(optionId)) return undefined;
  return books.find((book) => book.id === optionId);
}
